import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {runInNewContext} from 'node:vm';
import {execFileSync} from 'node:child_process';
const base = new URL('../source/theme.studio/usr/local/emhttp/plugins/theme.studio/', import.meta.url);
const php = readFileSync(new URL('include/theme.php', base), 'utf8');
const defaults = Object.fromEntries([...php.split('function theme_studio_validate')[0].matchAll(/'(\w+)' => ('[^']*'|true|false|\d+)/g)].map(([,key,value]) => [key, value.startsWith("'") ? value.slice(1,-1) : JSON.parse(value)]));
const element = {disabled:false, style:{setProperty(){}}, classList:{toggle(){}}, querySelector(){return this;}};
const root = {...element, querySelector(){return element;}, querySelectorAll(){return [];}};
const timers = new Map();
let counter = 0;
const context = {
  document:{getElementById(){return root;}},
  window:{ThemeStudioBootstrap:{defaults}, clearTimeout(id){timers.delete(id);}, setTimeout(fn){timers.set(++counter,fn);return counter;}}
};
const js = readFileSync(new URL('assets/theme-studio.js', base), 'utf8');
runInNewContext(js.replace('  buildColorControls();\n  bindEvents();\n  syncControls();', `
  globalThis.api = {importTheme, cssForTheme, presets, setState, moveHistory,
    edit(value) { state = Object.assign({}, state, value); scheduleHistory(); },
    getState() { return clone(state); }};`), context);
const {api} = context;
for (const invalid of [null, [], 'theme', {name:{}}, {enabled:'false'}, {accent:[]}]) assert.throws(() => api.importTheme(invalid));
assert.equal(api.importTheme({radius:999}).radius,24);
assert.equal(api.importTheme({radius:-4}).radius,0);
assert.equal(api.importTheme({animationSpeed:9,animationTimingVersion:1}).animationSpeed,45);
assert.equal(api.importTheme({animationSpeed:30,density:'normal'}).animationSpeed,15);
assert.equal(api.importTheme({name:'é'.repeat(60)}).name.length,48);
assert.equal(api.importTheme(JSON.parse('{"__proto__":{"bad":true},"unknown":1}')).unknown,undefined);
assert(!api.cssForTheme({...defaults,enabled:false}).includes('{'));
const css = api.cssForTheme({...defaults,name:'*/body{display:none}/*'});
assert(css.startsWith('/* Generated by UNRAID Theme Studio: body'));
assert.equal((css.match(/\*\//g)||[]).length,1);
for (const preset of Object.values(api.presets)) {
  const css = api.cssForTheme(preset);
  for (const [,variable] of php.matchAll(/^  (--[\w-]+):/gm)) assert(css.includes(variable + ':'), 'Export missing ' + variable);
  assert(css.includes('.status-green'));
  assert(!css.includes('#header .logo'), 'Stock logo must not be replaced');
}
if (process.env.PHP_BINARY) {
  const phpPath = new URL('include/theme.php', base).pathname.replace(/^\/(\w:)/,'$1');
  const normalize = css => css.replace(/\s/g,'').replace(/\d+\.\d+/g, number => String(Number(number)));
  for (const preset of [...Object.values(api.presets), {...defaults, transparency:37, gradientStrength:83, glowStrength:17, animatedBackground:true}, {...defaults,enabled:false}]) {
    const phpCss = execFileSync(process.env.PHP_BINARY,['-r',`require '${phpPath}'; echo theme_studio_css(json_decode(stream_get_contents(STDIN), true));`],{input:JSON.stringify(preset),encoding:'utf8'});
    assert.equal(normalize(api.cssForTheme(preset)),normalize(phpCss),'PHP and exported CSS must render identically');
  }
}
api.edit({radius:20});
api.moveHistory(-1);
assert.equal(api.getState().radius,defaults.radius);
for (const fn of timers.values()) fn();
api.moveHistory(1);
assert.equal(api.getState().radius,20);
api.edit({radius:23});
api.setState(api.presets.dracula);
api.moveHistory(-1);
assert.equal(api.getState().radius,23);
assert.equal(execFileSync(process.execPath,[new URL('sync-css.mjs',import.meta.url).pathname.replace(/^\/(\w:)/,'$1')],{encoding:'utf8'}),'','PHP and browser CSS templates have drifted');
console.log('Passed import validation, all preset exports, disabled export, comment escaping, history races, and CSS template parity.');
